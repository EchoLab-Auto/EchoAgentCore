/// TypeScript 绑定生成（`feature = "ts-bindings"`）。
///
/// ## 为什么由 Core 生成而不是 Panel 手写
///
/// 线格式的**唯一真值**是这里的 Rust 类型。此前 Panel 手抄了一份
/// `web/src/protocol.ts`（1116 行、55 个事件变体、73 个命令变体），
/// 靠人肉同步：
///
/// | 漂移形态 | 症状 |
/// |---|---|
/// | Core 加事件、Panel 没加 | `switch` 落到 `default`，静默忽略 |
/// | Core 改字段名 | `JSON.parse` 得到 `undefined`，渲染成空 |
/// | Core 改语义（文案/阈值） | 同一份数据刷新前后不一致 |
///
/// 三种都不报错。第三种真实发生过（定时消息文案，2026-11 修）。
///
/// ## 形状
///
/// 单文件、类型提升即可编译（TS 不要求声明顺序）。生成的类型名与 Rust
/// 类型名一致；`#[serde(...)]` 的 tag/content/rename/untagged 全部由
/// ts-rs 如实反映，见 `dump_protocol_ts` 的测试。
#[cfg(feature = "ts-bindings")]
pub mod ts_bindings {
    use ts_rs::TS;

    /// 生成结果里的文件头。Panel 侧的校验器据此确认「这是生成物，不是手写」。
    pub const HEADER: &str = "// @generated by `echo-agent-core dump-protocol-ts` — DO NOT EDIT.\n// 真值在 Core 的 `agent-module-management/src/protocol/`；改协议请改 Rust，\n// 然后重跑 Panel 仓的 `npm run sync-protocol`。\n\n\
// JSON 任意值（Rust 侧 `serde_json::Value`）。\n\
//\n\
// 刻意是 `unknown` 而**不是**递归的 JSON union：这些字段的语义是「Core 不\n\
// 约束形状，由消费方解读」（清单状态、远端供应商池、平台 session_labels…）。\n\
// 递归 union 会让消费方误以为可以逐层访问，却每次都要窄化；更糟的是它会让\n\
// 前端对含该字段的状态对象做深度类型运算时爆栈（`reactive()` 实例化过深）。\n\
// 消费方拿到的就是「不知道形状」，必须显式断言后使用——这正是实际情况。\n\
export type JsonValue = unknown;\n\n";

    /// 生成约定。
    ///
    /// **`large_int = "number"`**：ts-rs 默认把 `u64`/`i64` 映射成 `bigint`
    /// （怕超过 2^53），但这些字段走的是 **JSON**——`serde_json` 把 u64 序列化
    /// 成 JSON number，`JSON.parse` 拿到的是 `number`。标成 `bigint` 会让生成
    /// 的类型与运行期实际值不符（`Number.isInteger(x)` 为真但 `typeof x` 是
    /// `number`，TS 判成 `bigint` 就会逼调用方写无意义的转换）。
    ///
    /// 这些都是计数/序号/时间戳（seq、tokens、elapsed_ms、timestamp），
    /// 远在 2^53 以内。真需要大整数的协议字段应显式标 `#[ts(type = "string")]`。
    fn config() -> ts_rs::Config {
        ts_rs::Config::default().with_large_int("number")
    }

    fn decl<T: TS>() -> String {
        // ts-rs 12 的 `name()` / `decl()` 都要 `&Config`：它带着「这次导出的
        // 全局约定」（是否加 `export`、缩进、import 风格…）。用默认约定，
        // 与我们生成的单文件形状一致。
        // `decl()` 已经包含 `type X = …;` 整句，这里只补 `export`。
        let cfg = config();
        format!("export {}\n", T::decl(&cfg))
    }

    /// 全部线格式类型的 TypeScript 声明（单文件）。
    ///
    /// 清单是**手写的**——ts-rs 不做传递闭包收集。漏一个类型的后果是生成
    /// 文件缺声明（`tsc` 报错，编译期就能发现），比运行期漂移好得多。
    /// 新增协议类型时记得加进来；`export_includes_every_ws_type` 测试
    /// 会盯住"命令/事件的直接载荷类型都在里面"这件事。
    pub fn declarations() -> String {
        let mut out = String::from(HEADER);

        // ── 信封与根类型 ──
        out.push_str(&decl::<super::WsMessage>());
        out.push_str(&decl::<super::SequencedEvent>());
        out.push_str(&decl::<super::Emit>());
        out.push_str(&decl::<super::BackendCommand>());
        out.push_str(&decl::<super::BackendEvent>());

        // ── 命令/事件的载荷结构 ──
        out.push_str(&decl::<super::SkillSourceInfo>());
        out.push_str(&decl::<super::InstanceStatus>());
        out.push_str(&decl::<super::InstanceMetadataEntry>());
        out.push_str(&decl::<super::ShellSessionInfo>());
        out.push_str(&decl::<super::SessionInfo>());
        out.push_str(&decl::<super::ContextMessageInfo>());
        out.push_str(&decl::<super::ContextBlockInfo>());
        out.push_str(&decl::<super::TimelineSource>());
        out.push_str(&decl::<super::TimelineTool>());
        out.push_str(&decl::<super::TimelineMessage>());
        out.push_str(&decl::<super::BrowseRoot>());
        out.push_str(&decl::<super::SkillInfo>());
        out.push_str(&decl::<super::ToolInfo>());
        out.push_str(&decl::<super::TeamInfo>());
        out.push_str(&decl::<super::ModuleInfo>());
        out.push_str(&decl::<super::WorkspaceConversationInfo>());
        out.push_str(&decl::<super::WorkspaceSessionInfo>());
        out.push_str(&decl::<super::WorkspaceDirectory>());
        out.push_str(&decl::<super::WorkspaceGitInfo>());
        out.push_str(&decl::<super::WorkspaceChangedEntry>());
        out.push_str(&decl::<super::WorkspaceFileEntry>());
        out.push_str(&decl::<super::ApiProfileInfo>());
        out.push_str(&decl::<super::ApiMetricsEntry>());
        out.push_str(&decl::<super::ApiBalancePoint>());
        out.push_str(&decl::<super::ApiUsagePoint>());

        // ── 定义层与合作方 crate 的共享类型 ──
        out.push_str(&decl::<echo_defs::ThinkingMode>());
        out.push_str(&decl::<echo_defs::ReasoningEffort>());
        out.push_str(&decl::<agent_module_federation::FederationPeerInfo>());
        out.push_str(&decl::<agent_module_federation::FederatedNodeInfo>());
        out.push_str(&decl::<agent_module_federation::FederationLinkState>());

        out
    }
}
