//! 模块的**分类标签**（`ModuleManifest.tag`）。
//!
//! ## 与 `kind` 的分工
//!
//! | 字段 | 回答什么问题 | 谁消费 |
//! |---|---|---|
//! | `kind` | 这个模块属于哪一类**能力** | 门控作用域（人格级 / 进程级） |
//! | `tag` | 这个模块**从哪来** | 面板的分组展示 |
//!
//! 两者正交：同一类能力下既可能有随 Core 发布的实现，也可能有外部装入的
//! 实现。举例——工具类能力：内置工具集是 [`INNER`]，别人装进 `modules.toml`
//! 的子进程工具包是 [`OUTSIDE`]，两者 `kind` 都是 `tool`。
//!
//! ## 为什么只有两个值
//!
//! 分类是为了**让人在一屏内找到东西**，不是为了建模。取值越多，越容易
//! 变成"这一项到底该归哪"的反复讨论，而面板上多出来的组反而更难扫。
//! 需要更细的维度时加新的分组维度（面板已支持按 `kind` / 门控语义分组），
//! 而不是往 `tag` 里塞语义。
//!
//! ## 判定规则
//!
//! [`INNER`] = 编译进本二进制的模块（`BUILTIN_MODULE_IDS` 那批 + 外部仓编译
//! 进来的 workspace / prodoc / subagent）。它们随 Core 一起发版，改一个要重编译。
//!
//! [`OUTSIDE`] = 不随二进制走的东西：`modules.toml` 里声明的子进程模块、
//! 平台实例的门控壳（实现是独立进程的 `echo-adapter-*`）。
//!
//! 注意"外部仓编译进来的"（workspace / prodoc / subagent）**算 INNER**：
//! 它们以 git 依赖的形式参与 Core 构建，用户装 Core 就装上了它们，
//! 与"运行期往配置里加一行"完全是两件事。

/// 随宿主发布（编译进本二进制）。
pub const INNER: &str = "inner";

/// 不随二进制走（`modules.toml` 的子进程模块、平台实例壳）。
pub const OUTSIDE: &str = "outside";
