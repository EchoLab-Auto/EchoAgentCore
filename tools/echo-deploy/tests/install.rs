const DEPLOYMENT_CORE_LAUNCHER_SNAPSHOT: &str = r#"#!/bin/sh
# Generated by echo-deploy as render-only plan text; not installed or started.
# Trusted administrator launcher: resolves the durable current selector at
# exec time, so systemd never embeds a concrete release directory.
set -eu

selector='/home/evence/.local/state/echo-agent-core/deploy/current'
release_store='/home/evence/.local/state/echo-agent-core/releases'
core_config='/home/evence/.config/echo-agent-core/core.toml'
runtime_config='/home/evence/.local/state/echo-agent-core/runtime/runtime-adapter.json'

# The systemd backend invokes this same trusted launcher with no arguments
# and clears the environment except for this protocol marker.
if [ "${ECHO_DEPLOY_CONTROL_PROTOCOL:-}" = 'echo-deploy-control/1' ]; then
    exec '/home/evence/.local/libexec/echo-deploy/echo-deploy' runtime-adapter --config "$runtime_config"
fi

if ! target=$(readlink "$selector"); then
    echo "$0: cannot read current selector: $selector" >&2
    exit 1
fi
case "$target" in
    "$release_store"/*) ;;
    *)
        echo "$0: selector target is outside release_store: $target" >&2
        exit 1
        ;;
esac
release=${target#"$release_store"/}
case "$release" in
    ''|.*|*[!A-Za-z0-9._-]*)
        echo "$0: unsafe release id from selector: $release" >&2
        exit 1
        ;;
esac
if [ "${#release}" -gt 100 ]; then
    echo "$0: release id from selector is too long" >&2
    exit 1
fi
if [ ! -f "$target/bin/echo-agent-core" ] || [ ! -x "$target/bin/echo-agent-core" ]; then
    echo "$0: selected release has no executable bin/echo-agent-core: $target" >&2
    exit 1
fi

# ECHO_RELEASE_ID is a declaration derived from the durable selector.
# It is not a build ID and does not prove which executable is running.
ECHO_RELEASE_ID=$release
export ECHO_RELEASE_ID

has_config=0
for argument in "$@"; do
    case "$argument" in
        -c|--config|--config=*) has_config=1 ;;
    esac
done
if [ "$has_config" -eq 1 ]; then
    exec "$target/bin/echo-agent-core" "$@"
fi
exec "$target/bin/echo-agent-core" --config "$core_config" "$@"
"#;

