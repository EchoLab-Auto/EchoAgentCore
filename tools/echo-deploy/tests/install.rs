#[test]
fn timeouts_killmode_and_restart_policy_are_exact() {
    let mut spec = standalone_spec();
    spec.scope = InstallScope::System;
    let rendered = render_install(&spec).unwrap();

    let core = rendered.core_unit().unwrap().contents.as_str();
    let panel = rendered.panel_unit().unwrap().contents.as_str();
    let updater = rendered.updater_unit().unwrap().contents.as_str();

    assert_eq!(
        lines(core)
            .iter()
            .filter(|line| line.starts_with("TimeoutStopSec="))
            .copied()
            .collect::<Vec<_>>(),
        vec!["TimeoutStopSec=300"]
    );
    assert_eq!(
        lines(panel)
            .iter()
            .filter(|line| line.starts_with("TimeoutStopSec="))
            .copied()
            .collect::<Vec<_>>(),
        vec!["TimeoutStopSec=30"]
    );
    assert_eq!(
        lines(updater)
            .iter()
            .filter(|line| line.starts_with("TimeoutStartSec="))
            .copied()
            .collect::<Vec<_>>(),
        vec!["TimeoutStartSec=1800"]
    );
    for unit in [core, panel, updater] {
        assert!(unit.contains("KillMode=mixed\n"));
        assert!(unit.contains("KillSignal=SIGTERM\n"));
    }
    for unit in [core, panel] {
        assert!(unit.contains("Restart=always\n"));
        assert!(unit.contains("RestartSec=5s\n"));
        assert!(unit.contains("Type=simple\n"));
    }
    assert!(updater.contains("Type=oneshot\n"));
}

