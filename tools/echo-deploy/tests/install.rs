#[test]
fn deployment_units_guard_persistent_migration_activation() {
    let spec = standalone_deployment_spec();
    let rendered = spec.render().unwrap();
    let names = spec.unit_names();

    let guard = |unit: &str| {
        migration::activation_guard_line(
            &spec.deploy_executable,
            &spec.state_dir,
            &spec.instance_id,
            unit,
        )
        .unwrap()
    };
    let panel_name = names.panel.as_deref().unwrap();
    let core_guard = guard(&names.core);
    let panel_guard = guard(panel_name);
    let updater_guard = guard(&names.updater);

    for (line, unit) in [
        (&core_guard, names.core.as_str()),
        (&panel_guard, panel_name),
        (&updater_guard, names.updater.as_str()),
    ] {
        assert!(line.starts_with("ExecStartPre="), "{line}");
        assert!(line.contains("migration-mark-activation"), "{line}");
        assert!(line.contains(unit), "{line}");
        assert!(
            line.contains(&spec.state_dir.display().to_string()),
            "{line}"
        );
        assert!(line.contains(&spec.instance_id), "{line}");
    }
    for (left, right) in [
        (&core_guard, &panel_guard),
        (&core_guard, &updater_guard),
        (&panel_guard, &updater_guard),
    ] {
        assert_ne!(left, right);
    }
    assert!(!core_guard.contains(panel_name));
    assert!(!core_guard.contains(&names.updater));
    assert!(!panel_guard.contains(&names.core));
    assert!(!updater_guard.contains(&names.core));

    // Exactly one guard per unit, inside [Service], and the expected unit is
    // the only one referenced by that unit's own guard.
    for (file, expected) in [
        (rendered.core_unit().unwrap(), &core_guard),
        (rendered.panel_unit().unwrap(), &panel_guard),
        (rendered.updater_unit().unwrap(), &updater_guard),
    ] {
        let service = file
            .contents
            .split_once("[Service]\n")
            .expect("[Service] section")
            .1;
        let service = service.split("\n[Install]").next().unwrap();
        let guards = service
            .lines()
            .filter(|line| line.starts_with("ExecStartPre="))
            .collect::<Vec<_>>();
        assert_eq!(guards, vec![expected.as_str()], "{}", file.name);
        assert!(service.contains("NoNewPrivileges=true"), "{}", file.name);
    }

    // The guard must not displace the existing sandboxing contract.
    let core = rendered.core_unit().unwrap();
    let panel = rendered.panel_unit().unwrap();
    let updater = rendered.updater_unit().unwrap();
    assert!(core.contents.contains("PrivateTmp=true"));
    assert!(panel.contents.contains("PrivateTmp=true"));
    assert!(updater.contents.contains("PrivateTmp=false"));

    // `deployment = None` stays byte-identical: no ExecStartPre at all.
    let legacy = standalone_spec().render().unwrap();
    for unit in [
        legacy.core_unit().unwrap(),
        legacy.panel_unit().unwrap(),
        legacy.updater_unit().unwrap(),
    ] {
        assert!(!unit.contents.contains("ExecStartPre="), "{}", unit.name);
        assert!(!unit.contents.contains("migration-mark-activation"));
    }
}
