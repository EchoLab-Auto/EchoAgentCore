struct TempDeployment {
    root: tempfile::TempDir,
    spec: InstallSpec,
}

fn write_executable(path: &Path, contents: &str) {
    fs::write(path, contents).unwrap();
    fs::set_permissions(path, fs::Permissions::from_mode(0o755)).unwrap();
}

fn temp_deployment(standalone: bool) -> TempDeployment {
    let root = tempdir().unwrap();
    let base = root.path();
    let state = base.join("state");
    let instance = base.join("runtime");
    let store = base.join("releases");
    let source = base.join("core-source");
    let panel_source = base.join("panel-source");
    let config = base.join("config");
    let bin = base.join("bin");
    for dir in [&state, &instance, &store, &source, &config, &bin] {
        fs::create_dir_all(dir).unwrap();
        fs::set_permissions(dir, fs::Permissions::from_mode(0o700)).unwrap();
    }
    fs::set_permissions(&bin, fs::Permissions::from_mode(0o755)).unwrap();

    let release = store.join("r1");
    fs::create_dir_all(release.join("bin")).unwrap();
    fs::create_dir_all(release.join("web")).unwrap();
    write_executable(
        &release.join("bin/echo-agent-core"),
        "#!/bin/sh\nprintf 'release=%s\\n' \"${ECHO_RELEASE_ID-}\"\nprintf 'arg=%s\\n' \"$@\"\n",
    );
    write_executable(
        &release.join("bin/echo-agent-panel"),
        "#!/bin/sh\nprintf 'panel-arg=%s\\n' \"$@\"\n",
    );
    symlink(&release, state.join("current")).unwrap();

    let core_config = config.join("core.toml");
    let panel_config = config.join("panel.toml");
    fs::write(&core_config, "").unwrap();
    fs::write(&panel_config, "").unwrap();
    let deploy = base.join("deploy/echo-deploy");
    fs::create_dir_all(deploy.parent().unwrap()).unwrap();
    write_executable(&deploy, "#!/bin/sh\nprintf 'deploy-arg=%s\\n' \"$@\"\n");
    if standalone {
        fs::create_dir_all(&panel_source).unwrap();
        fs::write(instance.join("panel-gate.json"), "{}").unwrap();
    }

    let deployment = DeploymentRuntime {
        schema_version: DEPLOYMENT_RUNTIME_SCHEMA_VERSION,
        core_root: source,
        panel_root: standalone.then(|| panel_source.clone()),
        launcher_directory: bin.clone(),
        release_store: store.clone(),
        instance_state: instance.clone(),
        core_socket: instance.join("core.sock"),
        runtime_config: instance.join("runtime-adapter.json"),
        panel_gate_file: standalone.then(|| instance.join("panel-gate.json")),
        required_modules: vec![],
        acknowledge_external_writers_stopped: false,
    };
    let spec = InstallSpec {
        instance_id: "local-dev".into(),
        scope: InstallScope::User,
        release_root: state.join("current"),
        core_config,
        panel_config: standalone.then_some(panel_config),
        topology: if standalone {
            InstallTopology::Standalone
        } else {
            InstallTopology::CoreOnly
        },
        deploy_executable: deploy,
        state_dir: state,
        deployment: Some(deployment),
    };
    TempDeployment { root, spec }
}

fn install_plan_launchers(spec: &InstallSpec, plan: &Path) -> Vec<PathBuf> {
    let deployment = spec.deployment.as_ref().unwrap();
    let mut installed = Vec::new();
    for name in [
        Some(spec.unit_names().core_launcher),
        spec.unit_names().panel_launcher,
    ]
    .into_iter()
    .flatten()
    {
        let source = plan.join(&name);
        let target = deployment.launcher_directory.join(&name);
        let temporary = target.with_extension(format!("new.{}", std::process::id()));
        fs::copy(&source, &temporary).unwrap();
        fs::set_permissions(&temporary, fs::Permissions::from_mode(0o755)).unwrap();
        fs::rename(&temporary, &target).unwrap();
        installed.push(target);
    }
    installed
}

fn run_launcher(path: &Path, args: &[&str], envs: &[(&str, &str)]) -> std::process::Output {
    let mut command = Command::new(path);
    command.args(args).env_clear().env("PATH", "/usr/bin:/bin");
    for (key, value) in envs {
        command.env(key, value);
    }
    command.output().unwrap()
}

fn stdout(output: &std::process::Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}
