fn file<'a>(rendered: &'a RenderedInstall, name: &str) -> &'a InstallFile {
    rendered
        .file(name)
        .unwrap_or_else(|| panic!("missing rendered file {name}"))
}

fn lines(contents: &str) -> Vec<&str> {
    contents.lines().collect()
}

