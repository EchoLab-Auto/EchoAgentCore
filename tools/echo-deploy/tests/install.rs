#[test]
fn quote_injection_is_rejected_and_percent_dollar_are_escaped() {
    for bad in ["a\nb", "a\rb", "a\tb", "a\0b", "a\u{7f}b", "a\u{85}b"] {
        assert!(
            systemd_quote(bad).is_err(),
            "systemd_quote accepted {bad:?}"
        );
        assert!(
            systemd_path_value(bad).is_err(),
            "systemd_path_value accepted {bad:?}"
        );
        assert!(shell_quote(bad).is_err(), "shell_quote accepted {bad:?}");
        assert!(systemd_env_assignment("A", bad).is_err());
    }

    assert_eq!(systemd_quote("plain").unwrap(), "\"plain\"");
    assert_eq!(systemd_quote("a b").unwrap(), "\"a b\"");
    assert_eq!(systemd_quote("100%").unwrap(), "\"100%%\"");
    assert_eq!(systemd_quote("$HOME").unwrap(), "\"$$HOME\"");
    assert_eq!(systemd_quote("a\"b\\c;d#e").unwrap(), "\"a\\\"b\\\\c;d#e\"");
    assert_eq!(
        systemd_path_value("a b\"c\\d%e$f").unwrap(),
        "a\\x20b\\x22c\\\\d%%e$f"
    );
    assert_eq!(
        systemd_env_assignment("ECHO_AGENT_STATE_DIR", "/a b/100%").unwrap(),
        "\"ECHO_AGENT_STATE_DIR=/a b/100%%\""
    );
    assert_eq!(shell_quote("a'b").unwrap(), "'a'\\''b'");
    assert_eq!(
        systemd_executable_quote("/a b/100%/$x").unwrap(),
        "\"/a b/100%%/$x\""
    );
    for bad in ["/a\"b", "/a'b", "/a\\b", "/a\nb", ""] {
        assert!(
            systemd_executable_quote(bad).is_err(),
            "systemd_executable_quote accepted {bad:?}"
        );
    }

    let mut spec = base_spec();
    spec.release_root = PathBuf::from("/srv/echo 100% $dollar release");
    spec.core_config = PathBuf::from("/etc/echo/core 100% \"quoted\" $dollar back\\slash.toml");
    spec.state_dir = PathBuf::from("/var/lib/echo 100% \"quoted\" $dollar back\\slash");
    let rendered = render_install(&spec).unwrap();
    let core = rendered.core_unit().unwrap().contents.as_str();

    assert!(core.contains("WorkingDirectory=/srv/echo\\x20100%%\\x20$dollar\\x20release\n"));
    assert!(core.contains(
        "ExecStart=\"/srv/echo 100%% $dollar release/bin/echo-agent-core\" \"--config\" \"/etc/echo/core 100%% \\\"quoted\\\" $$dollar back\\\\slash.toml\"\n"
    ));
    assert!(core.contains("Environment=\"ECHO_AGENT_STATE_DIR=/var/lib/echo 100%% \\\"quoted\\\" $dollar back\\\\slash\"\n"));

    let launcher = file(&rendered, "echo-agent-local-dev").contents.clone();
    assert!(launcher.contains(
        r#"exec '/srv/echo 100% $dollar release/bin/echo-agent-core' --config '/etc/echo/core 100% "quoted" $dollar back\slash.toml' "$@""#
    ));
}

