#!/usr/bin/env python3
"""独立核验管理面协议契约产物（B3）——**不需要 Core 源码、不需要 Node/npm**。

把本文件与产物目录一起拷到任何一台有 Python 3.9+ 的机器（或 Panel 仓的 CI），
即可回答四个问题：

1. 这份 TS 是不是 Panel 固定的那一份？（sha256 对 `protocolCore.generatedSha256`）
2. 夹具齐不齐、有没有被改过？（清单集合 + 逐文件摘要 + 帧形状）
3. 产物内部是否自洽？（`SHA256SUMS` / `manifest.json` / 聚合摘要三方互证）
4. 它来自哪个 Core 提交、是不是未提交的工作树？（来源字段）

退出码：0 = 通过；1 = 校验失败；2 = 用法错误。失败行形如
`✗ [E_TS_DIGEST] …`，便于 CI 与测试断言具体是哪一条闸失效。

设计约束：单文件、只用标准库、只读产物目录（不写任何文件）。
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

TS_NAME = "protocol.generated.ts"
MANIFEST_NAME = "manifest.json"
SUMS_NAME = "SHA256SUMS"
INDEX_NAME = "fixtures.index.json"
SCHEMA = "echo-agent.protocol-contract/1"
FIXTURE_SCHEMA = "echo-agent.protocol-contract.fixtures/1"
HEX40 = re.compile(r"^[0-9a-f]{40}$")
HEX64 = re.compile(r"^[0-9a-f]{64}$")
HEADER_MARK = b"// @generated by `echo-agent-core dump-protocol-ts` \xe2\x80\x94 DO NOT EDIT."
REQUIRED_TS_TYPES = (
    b"export type JsonValue = unknown;",
    b"export type WsMessage",
    b"export type BackendCommand",
    b"export type BackendEvent",
)
SUMS_LINE = re.compile(r"^([0-9a-f]{64})  ([^\s].*)$")


class Failure(Exception):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def fail(code: str, message: str) -> None:
    raise Failure(code, message)


def safe_rel(raw: object) -> str:
    """只接受产物内的相对路径；拒绝绝对路径 / .. / 反斜杠 / 空段。"""
    if not isinstance(raw, str) or not raw:
        fail("E_LAYOUT", f"非法路径字段：{raw!r}")
    if raw.startswith("/") or ".." in raw.split("/") or "\\" in raw or raw.endswith("/"):
        fail("E_LAYOUT", f"路径必须留在产物目录内：{raw!r}")
    return raw


def list_files(root: Path) -> list[str]:
    found = []
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            fail("E_LAYOUT", f"产物里不允许符号链接：{path.relative_to(root)}")
        if path.is_file():
            found.append(path.relative_to(root).as_posix())
    return found


def read_json(path: Path, code: str) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(code, f"缺少文件：{path.name}")
    except (UnicodeDecodeError, json.JSONDecodeError) as err:
        fail(code, f"{path.name} 不是合法 UTF-8 JSON：{err}")
    if not isinstance(data, dict):
        fail(code, f"{path.name} 顶层必须是对象")
    return data


def parse_sums(path: Path) -> dict[str, str]:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        fail("E_LAYOUT", f"缺少 {SUMS_NAME}")
    except UnicodeDecodeError as err:
        fail("E_SUMS_FORMAT", f"{SUMS_NAME} 不是 UTF-8：{err}")
    entries: dict[str, str] = {}
    for lineno, line in enumerate(text.splitlines(), start=1):
        if not line.strip():
            continue
        match = SUMS_LINE.match(line)
        if not match:
            fail("E_SUMS_FORMAT", f"{SUMS_NAME}:{lineno} 不是「<sha256>  <path>」：{line!r}")
        digest, rel = match.groups()
        rel = safe_rel(rel)
        if rel in entries:
            fail("E_SUMS_FORMAT", f"{SUMS_NAME}:{lineno} 重复列出 {rel}")
        entries[rel] = digest
    if not entries:
        fail("E_SUMS_FORMAT", f"{SUMS_NAME} 是空的")
    return entries


def derive_fixture(path: Path, rel: str) -> dict:
    data = read_json(path, "E_FIXTURE_INVALID")
    frame = data.get("type")
    if frame not in ("event", "command"):
        fail("E_FIXTURE_INVALID", f"{rel}: 顶层 type 必须是 event/command（实际 {frame!r}）")
    payload = data.get("payload")
    if not isinstance(payload, dict) or len(payload) != 1:
        fail("E_FIXTURE_INVALID", f"{rel}: payload 必须恰好一个变体键")
    variant, body = next(iter(payload.items()))
    if not isinstance(body, dict):
        fail("E_FIXTURE_INVALID", f"{rel}: payload.{variant} 必须是对象")
    seq = data.get("seq")
    if seq is not None and not isinstance(seq, int):
        fail("E_FIXTURE_INVALID", f"{rel}: seq 必须是整数或缺省")
    if frame == "command" and seq is not None:
        fail("E_FIXTURE_INVALID", f"{rel}: 命令帧不应带顶层 seq")
    return {
        "path": rel,
        "sha256": sha256_file(path),
        "bytes": path.stat().st_size,
        "frame": frame,
        "variant": variant,
        "seq": seq,
        "payload_keys": sorted(body.keys()),
    }


def verify(artifact: Path, expected_ts: str | None, expected_commit: str | None, require_fixtures: int) -> dict:
    if not artifact.is_dir():
        fail("E_LAYOUT", f"产物目录不存在：{artifact}")
    for name in (TS_NAME, MANIFEST_NAME, SUMS_NAME, INDEX_NAME):
        if not (artifact / name).is_file():
            fail("E_LAYOUT", f"缺少必需文件：{name}")
    if not (artifact / "fixtures").is_dir():
        fail("E_LAYOUT", "缺少 fixtures/ 目录")

    manifest = read_json(artifact / MANIFEST_NAME, "E_MANIFEST_SCHEMA")
    if manifest.get("schema") != SCHEMA:
        fail("E_MANIFEST_SCHEMA", f"manifest.schema 应为 {SCHEMA}，实际 {manifest.get('schema')!r}")
    contract = manifest.get("contract")
    source = manifest.get("source")
    entries = manifest.get("files")
    if not isinstance(contract, dict) or not isinstance(source, dict) or not isinstance(entries, list):
        fail("E_MANIFEST_SCHEMA", "manifest 缺少 contract / source / files")

    # ── 1. 文件集合：manifest 与磁盘必须互为子集（少文件=缺夹具，多文件=夹带）──
    actual = set(list_files(artifact)) - {SUMS_NAME, MANIFEST_NAME}
    listed = {}
    for entry in entries:
        if not isinstance(entry, dict):
            fail("E_MANIFEST_SCHEMA", "manifest.files 的元素必须是对象")
        rel = safe_rel(entry.get("path"))
        if rel in listed:
            fail("E_MANIFEST_SCHEMA", f"manifest.files 重复列出 {rel}")
        if not isinstance(entry.get("bytes"), int):
            fail("E_MANIFEST_SCHEMA", f"manifest.files[{rel}].bytes 必须是整数")
        listed[rel] = entry
    missing = sorted(actual - set(listed))
    unlisted = sorted(set(listed) - actual)
    if missing:
        fail("E_FILE_SET", f"产物里有未登记的载荷文件：{', '.join(missing)}")
    if unlisted:
        fail("E_FILE_SET", f"manifest 登记了不存在的文件（缺夹具？）：{', '.join(unlisted)}")

    # ── 2. 逐文件摘要 ──
    for rel, entry in sorted(listed.items()):
        path = artifact / rel
        digest = sha256_file(path)
        if digest != entry.get("sha256"):
            fail("E_MANIFEST_HASH", f"{rel} 摘要不符：manifest {entry.get('sha256')} / 实际 {digest}")
        if path.stat().st_size != entry["bytes"]:
            fail("E_MANIFEST_HASH", f"{rel} 字节数不符：manifest {entry['bytes']} / 实际 {path.stat().st_size}")

    # ── 3. SHA256SUMS 三方互证（含 manifest 自身）──
    sums = parse_sums(artifact / SUMS_NAME)
    expected_sums = dict(listed)
    expected_sums[MANIFEST_NAME] = {
        "sha256": sha256_file(artifact / MANIFEST_NAME),
        "bytes": (artifact / MANIFEST_NAME).stat().st_size,
    }
    if set(sums) != set(expected_sums):
        missing_sums = sorted(set(expected_sums) - set(sums))
        extra_sums = sorted(set(sums) - set(expected_sums))
        detail = []
        if missing_sums:
            detail.append(f"未列入：{', '.join(missing_sums)}")
        if extra_sums:
            detail.append(f"多出：{', '.join(extra_sums)}")
        fail("E_SUMS_MISMATCH", f"{SUMS_NAME} 与 manifest 不一致（{'；'.join(detail)}）")
    for rel, digest in sorted(sums.items()):
        actual_digest = sha256_file(artifact / rel)
        if digest != actual_digest:
            fail("E_SUMS_MISMATCH", f"{rel} 在 {SUMS_NAME} 里的摘要与实际不符（错 hash？）")

    # ── 4. TS 正文 ──
    ts_path = artifact / TS_NAME
    ts_bytes = ts_path.read_bytes()
    ts_sha = sha256_file(ts_path)
    if not ts_bytes.strip():
        fail("E_TS_DIGEST", "TS 正文为空")
    if b"\r" in ts_bytes:
        fail("E_TS_ENCODING", "TS 正文含 CR（跨平台换行污染）")
    if not ts_bytes.endswith(b"\n"):
        fail("E_TS_ENCODING", "TS 正文末尾缺换行")
    try:
        ts_bytes.decode("utf-8")
    except UnicodeDecodeError as err:
        fail("E_TS_ENCODING", f"TS 正文不是 UTF-8：{err}")
    if not ts_bytes.startswith(HEADER_MARK):
        fail("E_TS_HEADER", "TS 正文缺 `@generated` 头——可能被手改或不是本生成器产物")
    for marker in REQUIRED_TS_TYPES:
        if marker not in ts_bytes:
            fail("E_TS_HEADER", f"TS 正文缺关键声明：{marker.decode('utf-8', 'replace')}")
    if contract.get("ts_sha256") != ts_sha:
        fail("E_TS_DIGEST", f"manifest.contract.ts_sha256 与实际不符：{contract.get('ts_sha256')} / {ts_sha}")
    ts_entry = listed.get(TS_NAME)
    if not ts_entry or ts_entry.get("sha256") != ts_sha:
        fail("E_TS_DIGEST", "manifest.files 里的 TS 摘要与实际不符")
    if contract.get("ts_bytes") != len(ts_bytes):
        fail("E_TS_DIGEST", "manifest.contract.ts_bytes 与实际不符")
    if expected_ts and ts_sha != expected_ts.lower():
        fail("E_TS_DIGEST", f"TS 摘要与预期不符：预期 {expected_ts.lower()} / 实际 {ts_sha}")

    # ── 5. 夹具清单（缺一个、改一字节都要报）──
    index = read_json(artifact / INDEX_NAME, "E_FIXTURE_INDEX")
    if index.get("schema") != FIXTURE_SCHEMA:
        fail("E_FIXTURE_INDEX", f"{INDEX_NAME}.schema 应为 {FIXTURE_SCHEMA}")
    fixtures = index.get("fixtures")
    if not isinstance(fixtures, list):
        fail("E_FIXTURE_INDEX", f"{INDEX_NAME}.fixtures 必须是数组")
    indexed = {}
    for entry in fixtures:
        if not isinstance(entry, dict):
            fail("E_FIXTURE_INDEX", f"{INDEX_NAME}.fixtures 的元素必须是对象")
        rel = safe_rel(entry.get("path"))
        if not rel.startswith("fixtures/"):
            fail("E_FIXTURE_INDEX", f"夹具路径必须在 fixtures/ 下：{rel}")
        if rel in indexed:
            fail("E_FIXTURE_INDEX", f"{INDEX_NAME} 重复列出 {rel}")
        indexed[rel] = entry
    disk_fixtures = {rel for rel in actual if rel.startswith("fixtures/")}
    if sorted(disk_fixtures - set(indexed)):
        fail("E_FIXTURE_MISSING", f"夹具未登记（可能被夹带）：{', '.join(sorted(disk_fixtures - set(indexed)))}")
    if sorted(set(indexed) - disk_fixtures):
        fail("E_FIXTURE_MISSING", f"夹具缺失：{', '.join(sorted(set(indexed) - disk_fixtures))}")
    if index.get("count") != len(indexed) or contract.get("fixtures", {}).get("count") != len(indexed):
        fail("E_FIXTURE_INDEX", "夹具计数与实际不一致")
    if require_fixtures and len(indexed) < require_fixtures:
        fail("E_FIXTURE_MISSING", f"夹具只有 {len(indexed)} 个，少于要求的 {require_fixtures} 个")
    for rel, entry in sorted(indexed.items()):
        derived = derive_fixture(artifact / rel, rel)
        for key in ("sha256", "bytes", "frame", "variant", "seq", "payload_keys"):
            if entry.get(key) != derived[key]:
                fail("E_FIXTURE_INDEX", f"{rel} 的 {key} 与索引不符（夹具被改过？）")
        if listed.get(rel, {}).get("sha256") != derived["sha256"]:
            fail("E_MANIFEST_HASH", f"{rel} 在 manifest.files 里的摘要与夹具实际不符")

    # ── 6. 聚合摘要（把「TS + 夹具」当作一个整体钉住）──
    digest = hashlib.sha256()
    for rel in sorted(listed):
        digest.update(rel.encode("utf-8"))
        digest.update(b"\0")
        digest.update(listed[rel]["sha256"].encode("ascii"))
        digest.update(b"\n")
    if digest.hexdigest() != contract.get("aggregate_sha256"):
        fail("E_AGGREGATE", f"聚合摘要不符：manifest {contract.get('aggregate_sha256')} / 重算 {digest.hexdigest()}")

    # ── 7. 来源 ──
    commit = source.get("commit")
    if not isinstance(commit, str) or not HEX40.match(commit):
        fail("E_SOURCE_COMMIT", f"source.commit 必须是完整 40 位提交：{commit!r}")
    if not isinstance(source.get("dirty"), bool):
        fail("E_SOURCE_COMMIT", "source.dirty 必须是布尔值")
    if source.get("dirty") and expected_commit:
        fail("E_SOURCE_COMMIT", "来源是未提交工作树（dirty=true），不能当作固定提交的产物")
    if expected_commit and commit != expected_commit.lower():
        fail("E_SOURCE_COMMIT", f"提交不符：预期 {expected_commit.lower()} / 实际 {commit}")
    if source.get("crate") != "echo-protocol":
        fail("E_SOURCE_COMMIT", f"source.crate 应为 echo-protocol，实际 {source.get('crate')!r}")

    return {
        "ok": True,
        "artifact": str(artifact),
        "version": contract.get("version"),
        "ts_sha256": ts_sha,
        "ts_bytes": len(ts_bytes),
        "fixtures": len(indexed),
        "aggregate_sha256": contract.get("aggregate_sha256"),
        "commit": commit,
        "dirty": source.get("dirty"),
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description="独立核验管理面协议契约产物（不需要 Core 源码）",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "示例：\n"
            "  python3 verify-protocol-contract.py ./protocol-contract-0.3.1\n"
            "  python3 verify-protocol-contract.py ./protocol-contract-0.3.1 \\\n"
            "      --expect-ts-sha256 \"$(node -p \"require('./web/package.json').protocolCore.generatedSha256\")\"\n"
        ),
    )
    parser.add_argument("artifact", help="产物目录（解压后的 protocol-contract-<version>/）")
    parser.add_argument("--expect-ts-sha256", help="预期 TS 摘要（hex64）；建议取 Panel protocolCore.generatedSha256")
    parser.add_argument("--expect-commit", help="预期 Core 提交（40 位）")
    parser.add_argument("--require-fixtures", type=int, default=0, help="至少需要多少个夹具（发版可传 8）")
    parser.add_argument("--json", action="store_true", help="以 JSON 输出结果")
    args = parser.parse_args()

    if args.expect_ts_sha256 and not HEX64.match(args.expect_ts_sha256.lower()):
        print(f"✗ [E_USAGE] --expect-ts-sha256 不是 64 位十六进制：{args.expect_ts_sha256}", file=sys.stderr)
        return 2
    if args.expect_commit and not HEX40.match(args.expect_commit.lower()):
        print(f"✗ [E_USAGE] --expect-commit 不是 40 位提交：{args.expect_commit}", file=sys.stderr)
        return 2

    try:
        result = verify(
            Path(args.artifact).resolve(),
            args.expect_ts_sha256,
            args.expect_commit,
            args.require_fixtures,
        )
    except Failure as failure:
        if args.json:
            print(json.dumps({"ok": False, "code": failure.code, "message": failure.message}, ensure_ascii=False))
        else:
            print(f"✗ [{failure.code}] {failure.message}", file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(result, ensure_ascii=False))
    else:
        print("✓ 契约产物通过核验")
        print(f"  version   {result['version']}")
        print(f"  ts sha256 {result['ts_sha256']} ({result['ts_bytes']} B)")
        print(f"  fixtures  {result['fixtures']}")
        print(f"  aggregate {result['aggregate_sha256']}")
        print(f"  source    {result['commit']} dirty={str(result['dirty']).lower()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
